/// Everything the "looking for eyes" face needs to draw one frame.
///
/// All lengths are in the 1080x750 "face space" of the reference clip
/// (the 1440x1000 face band of the 1440x2560 video, scaled by 0.75).
/// Left-eye geometry is stored in absolute face-space x; the right eye is the
/// mirror image about `axis`. Values were measured frame by frame from
/// `Vedio/looking for eyes.mp4` (152 frames @ 30 fps).
public struct LookingForEyesPose: Equatable, Sendable {
    /// Fractional 1-based frame number of the source clip.
    public var frame: Double
    /// x of the mirror axis between the eyes (the face sways with it).
    public var axis: Double
    /// y of the lowest point of the grey outer eye ring.
    public var ringBottom: Double
    /// Left edge of the left ring, relative to `axis`.
    public var ringLeftRel: Double
    /// Distance between ring bottom and white-of-the-eye bottom.
    public var whiteGap: Double
    /// Horizontal gaze shift of both pupils (same direction), vs. resting.
    public var pupilShift: Double
    /// Reference y of the pupil: its lowest point is `pupilY + 84`.
    public var pupilY: Double
    /// Horizontal pupil radius (vertical radius stays 85.7); widens as the face turns angrier.
    public var pupilRadiusX: Double
    /// Highlight offset from the pupil centre.
    public var highlightRelX: Double
    public var highlightRelY: Double
    public var highlightAlpha: Double
    /// Eyelid cut line: 9 y values at x = ringLeft + 12 + 34.5 * k.
    public var lid: [Double]
    /// Brow outline of the left eye: 9 samples of (x relative to axis, top y, bottom y).
    public var brow: [Double]
    /// Lid-crease outline of the left eye, same layout as `brow`.
    public var crease: [Double]
    /// xa, ya, xb, yb, then (x, top, bottom) at three interior points.
    public var mouth: [Double]
    /// Blue electric flicker intensity inside the pupils (0...1).
    public var spark: Double
    /// Fire coverage 0...1 (1 = pupils fully ablaze).
    public var fireLevel: Double
    /// y of the highest flame tip.
    public var fireTop: Double
    /// Ember sprinkle intensity 0...1.
    public var embers: Double
    /// 1 = lids as measured, 0 = fully shut (choreography scales `lid` toward the eyeball bottom).
    public var lidOpenness: Double = 1
    /// Radius of the iris / pupil (the clip's pupil is 85.7 tall; the exercise phase fits it to the opening).
    public var irisRadius: Double = 85.7
}

public enum LookingForEyesTimeline {
    public static let fps: Double = 30
    public static let frameCount = 152
    public static let duration: TimeInterval = Double(frameCount) / fps

    /// Pose at `t` seconds; wraps modulo `duration` so the clip loops.
    public static func pose(at t: TimeInterval) -> LookingForEyesPose {
        var wrapped = t.truncatingRemainder(dividingBy: duration)
        if wrapped < 0 { wrapped += duration }
        let fp = wrapped * fps + 1          // 1-based, [1, 153)
        let a = dense(fp)
        let (lid, brow, crease) = shapes(fp)
        return LookingForEyesPose(
            frame: fp,
            axis: a[0], ringBottom: a[1],
            ringLeftRel: lid.rel, whiteGap: lid.gap,
            pupilShift: a[2], pupilY: a[3],
            pupilRadiusX: keyed(pupilRadiusKeys, fp),
            highlightRelX: a[4], highlightRelY: a[5],
            highlightAlpha: keyed(hlAlphaKeys, fp),
            lid: lid.values, brow: brow, crease: crease,
            mouth: Array(a[6..<19]),
            spark: keyed(sparkKeys, fp),
            fireLevel: keyed(fireLevelKeys, fp),
            fireTop: keyed(fireTopKeys, fp),
            embers: keyed(emberKeys, fp)
        )
    }

    // MARK: Interpolation

    private static func keyed(_ keys: [(Double, Double)], _ fp: Double) -> Double {
        guard let first = keys.first, let last = keys.last else { return 0 }
        if fp <= first.0 { return first.1 }
        if fp >= last.0 { return last.1 }
        for i in 1..<keys.count where fp <= keys[i].0 {
            let (f0, v0) = keys[i - 1], (f1, v1) = keys[i]
            return v0 + (v1 - v0) * (fp - f0) / (f1 - f0)
        }
        return last.1
    }

    private static func dense(_ fp: Double) -> [Double] {
        let i = min(frameCount - 1, max(0, Int(fp) - 1))
        let k = fp - Double(i + 1)
        let r0 = denseRows[i], r1 = denseRows[(i + 1) % frameCount]
        return zip(r0, r1).map { $0 + ($1 - $0) * k }
    }

    private struct Lid { var rel: Double; var gap: Double; var values: [Double] }

    private static func shapes(_ fp: Double) -> (Lid, [Double], [Double]) {
        let keys = shapeRows
        var lo = 0
        for i in 0..<keys.count where keys[i].frame <= fp { lo = i }
        let hi = min(lo + 1, keys.count - 1)
        let a = keys[lo], b = keys[hi]
        let k = hi == lo ? 0 : (fp - a.frame) / (b.frame - a.frame)
        let v = zip(a.values, b.values).map { $0 + ($1 - $0) * k }
        return (Lid(rel: v[0], gap: v[1], values: Array(v[2..<11])),
                Array(v[11..<38]), Array(v[38..<65]))
    }

